"""Write backend/src/bleep/incidents/quote_lookalikes.py: every character that can read as a
quote in an incident title (#311).

A character is in the set when, after NFC (what `title_name` does first):
- its confusable skeleton (UTS #39: NFD, the confusables.txt map, NFD again) is made only of `'`
  (the skeleton of `"` is `''`), or is once its combining marks are left out and NFC keeps the
  character whole (the Greek `῎`, a breathing and an accent drawn as two ticks; what NFC changes
  is looked up as what NFC makes of it), or
- it is an opening or closing quote (Unicode categories Pi and Pf), or
- its Unicode name says it is a quotation mark (the low „ and ⹂, 〝 〞 〟 and the ornaments ❝ ❞,
  which are Ps, Pe or So and have skeletons of their own), or
- its NFKC form holds `'`, `"`, `“` or `”`, or
- it is one of `MISSING`: single characters drawn as a double quote mark that confusables.txt
  18.0.0 leaves out.

Pass a downloaded copy of https://www.unicode.org/Public/security/latest/confusables.txt:

    uv run --project backend python scripts/quote_lookalikes.py path/to/confusables.txt
"""

import re
import sys
import unicodedata
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "backend/src/bleep/incidents/quote_lookalikes.py"
QUOTES = ("'", '"', "\u201c", "\u201d")
# ˵ is the grave twin of ˶ (which confusables.txt maps to `"`); ᐥ is drawn as ˝.
MISSING = {
    0x02F5,  # MODIFIER LETTER MIDDLE DOUBLE GRAVE ACCENT
    0x1425,  # CANADIAN SYLLABICS FINAL DOUBLE ACUTE
}


def read_map(path: Path) -> tuple[dict[str, str], str, str]:
    """The confusables map, and the file's version and date lines."""
    table: dict[str, str] = {}
    version = date = "?"
    for raw in path.read_text(encoding="utf-8-sig").splitlines():
        if found := re.match(r"#\s*Version:\s*(.+)", raw):
            version = found.group(1).strip()
        if found := re.match(r"#\s*Date:\s*(.+)", raw):
            date = found.group(1).strip()
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        source, target, *_ = (part.strip() for part in line.split(";"))
        to_text = "".join(chr(int(h, 16)) for h in target.split())
        table["".join(chr(int(h, 16)) for h in source.split())] = to_text
    return table, version, date


def _marks_off(text: str) -> set[str]:
    """The characters of `text` but its combining marks, which `title_name` drops."""
    return {c for c in text if unicodedata.category(c) not in ("Mn", "Me")}


def lookalikes(table: dict[str, str]) -> list[int]:
    def skeleton(text: str) -> str:
        text = unicodedata.normalize("NFD", text)
        return unicodedata.normalize("NFD", "".join(table.get(c, c) for c in text))

    found = []
    for code in range(0x110000):
        if 0xD800 <= code <= 0xDFFF:
            continue
        char = chr(code)
        drawn = skeleton(char)
        if (
            (drawn and set(drawn) == {"'"})
            or (unicodedata.normalize("NFC", char) == char and _marks_off(drawn) == {"'"})
            or unicodedata.category(char) in ("Pi", "Pf")
            or "QUOTATION MARK" in unicodedata.name(char, "")
            or any(q in unicodedata.normalize("NFKC", char) for q in QUOTES)
            or code in MISSING
        ):
            found.append(code)
    return found


def main() -> None:
    table, version, date = read_map(Path(sys.argv[1]))
    lines = [
        '"""Every character that can read as a quote in an incident title (#311).',
        "",
        f"Generated by scripts/quote_lookalikes.py from Unicode's confusables.txt {version}",
        f"({date}), with Python's Unicode {unicodedata.unidata_version} for NFC, NFKC and the",
        "categories, and the script's MISSING. Do not edit by hand; run the script again on a",
        "newer confusables.txt.",
        '"""',
        "",
        "QUOTE_LOOKALIKES = frozenset(",
        "    chr(code)",
        "    for code in (",
    ]
    codes = lookalikes(table)
    for code in codes:
        name = unicodedata.name(chr(code), "?")
        lines.append(f"        0x{code:04X},  # {name}")
    lines += ["    )", ")", ""]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT} ({len(codes)} characters)")


if __name__ == "__main__":
    main()
